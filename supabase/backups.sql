-- 공중도시 DEEP LAYER · 서버 백업 (Supabase SQL Editor에 통째로 붙여넣어 실행 / 여러 번 실행해도 안전)
-- 먼저 schema.sql 이 실행되어 있어야 한다 (saves 표 필요).
-- 동작: 서버 저장(saves)이 덮어써지기 직전의 진행을 유저별로 최대 12개까지 보관한다.
--   · 6시간에 한 번 자동 백업 / 캐릭터가 있던 저장이 캐릭터 없는 빈 상태로 덮일 때는 항상 백업(안전장치)
--   · '지금 백업' 버튼(수동)도 같은 12개 안에 들어간다. 캐릭터가 없는 빈 상태는 백업하지 않는다.
-- 용량: 저장 1개 ≈ 수십 KB × 12개 × 유저 수. 30명이면 수십 MB 이하.

create table if not exists public.save_backups (
  id      bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  rev     int not null,
  kind    text not null default 'auto',     -- auto | guard | manual
  at      timestamptz not null default now(),
  data    jsonb not null
);
create index if not exists save_backups_user_at on public.save_backups (user_id, at desc);
alter table public.save_backups enable row level security;   -- 정책 없음 = 직접 접근 불가, 아래 함수로만

-- 보관 개수 정리 (유저당 최근 12개만)
create or replace function public._trim_backups(p_uid uuid) returns void
language sql security definer set search_path = public as $$
  delete from public.save_backups
   where user_id = p_uid
     and id not in (select id from public.save_backups where user_id = p_uid order by at desc, id desc limit 12);
$$;
revoke all on function public._trim_backups(uuid) from public, anon, authenticated;

-- 저장이 덮어써지기 직전(BEFORE UPDATE)에 이전 진행을 백업
create or replace function public.trg_backup_save() returns trigger
language plpgsql security definer set search_path = public as $$
declare last_at timestamptz; old_ok boolean; new_ok boolean; why text;
begin
  old_ok := coalesce(old.data->>'created', '') = 'true';
  new_ok := coalesce(new.data->>'created', '') = 'true';
  if not old_ok then return new; end if;                       -- 캐릭터가 없던 빈 저장은 보관하지 않는다
  select max(at) into last_at from public.save_backups where user_id = old.user_id;
  if not new_ok then why := 'guard';                            -- 캐릭터 있는 저장이 빈 상태로 덮이는 경우: 항상 백업
  elsif last_at is null or last_at < now() - interval '6 hours' then why := 'auto';
  else return new; end if;
  insert into public.save_backups(user_id, rev, kind, data) values (old.user_id, old.rev, why, old.data);
  perform public._trim_backups(old.user_id);
  return new;
end $$;
drop trigger if exists trg_backup_save on public.saves;
create trigger trg_backup_save before update on public.saves for each row execute function public.trg_backup_save();

-- 내 백업 목록 (최신순): 화면에 보여 줄 요약만
create or replace function public.list_backups() returns jsonb
language sql security definer set search_path = public as $$
  select coalesce(jsonb_agg(jsonb_build_object(
    'id', id, 'at', at, 'rev', rev, 'kind', kind,
    'name', left(coalesce(data->'character'->>'name', ''), 12),
    'level', coalesce(data->'character'->>'level', ''),
    'money', coalesce(data->>'money', '')
  ) order by at desc, id desc), '[]'::jsonb)
  from public.save_backups where user_id = auth.uid();
$$;

-- 백업 하나 통째로 (내 것만)
create or replace function public.get_backup(p_id bigint) returns jsonb
language sql security definer set search_path = public as $$
  select data from public.save_backups where id = p_id and user_id = auth.uid();
$$;

-- 지금 백업 (현재 서버 저장을 수동 백업, 1분에 한 번)
create or replace function public.backup_now() returns jsonb
language plpgsql security definer set search_path = public as $$
declare uid uuid := auth.uid(); s record;
begin
  if uid is null then raise exception 'no_auth'; end if;
  select rev, data into s from public.saves where user_id = uid;
  if not found or coalesce(s.data->>'created', '') <> 'true' then return jsonb_build_object('ok', false, 'why', 'nothing'); end if;
  if exists (select 1 from public.save_backups where user_id = uid and kind = 'manual' and at > now() - interval '1 minute') then
    return jsonb_build_object('ok', false, 'why', 'too_fast');
  end if;
  insert into public.save_backups(user_id, rev, kind, data) values (uid, s.rev, 'manual', s.data);
  perform public._trim_backups(uid);
  return jsonb_build_object('ok', true);
end $$;

-- 내 백업 하나 삭제 (내 것만)
create or replace function public.delete_backup(p_id bigint) returns jsonb
language plpgsql security definer set search_path = public as $$
declare n int;
begin
  if auth.uid() is null then raise exception 'no_auth'; end if;
  delete from public.save_backups where id = p_id and user_id = auth.uid();
  get diagnostics n = row_count;
  return jsonb_build_object('ok', n > 0);
end $$;

revoke all on function public.list_backups() from public, anon;
revoke all on function public.get_backup(bigint) from public, anon;
revoke all on function public.backup_now() from public, anon;
grant execute on function public.list_backups() to authenticated;
grant execute on function public.get_backup(bigint) to authenticated;
grant execute on function public.backup_now() to authenticated;
revoke all on function public.delete_backup(bigint) from public, anon;
grant execute on function public.delete_backup(bigint) to authenticated;
